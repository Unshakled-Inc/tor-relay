package render

import (
	"fmt"
	"os"
	"strings"

	"github.com/Unshakled-Inc/tor-relay/internal/config"
)

// TorrcD is the directory operators can drop extra configuration into.
const TorrcD = "/etc/tor/torrc.d"

// IncludeTorrcD reports whether dir exists and contains at least one *.conf
// file. Only then does torinit add the %include line.
func IncludeTorrcD(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".conf") {
			return true
		}
	}
	return false
}

// Render returns the middle-relay torrc in the fixed directive order.
func Render(cfg *config.Config, dataDir string, includeTorrcD bool) string {
	var b strings.Builder

	b.WriteString("# generated by torinit, do not edit\n")
	fmt.Fprintf(&b, "DataDirectory %s\n", dataDir)
	fmt.Fprintf(&b, "Log %s stdout\n", cfg.LogLevel)
	b.WriteString("RunAsDaemon 0\n")
	b.WriteString("SocksPort 0\n")
	fmt.Fprintf(&b, "Nickname %s\n", cfg.Nickname)
	fmt.Fprintf(&b, "ContactInfo %s\n", cfg.Contact)
	fmt.Fprintf(&b, "ORPort %d\n", cfg.ORPort)
	if cfg.Address != "" {
		fmt.Fprintf(&b, "Address %s\n", cfg.Address)
	}
	if cfg.BandwidthRate != "" {
		fmt.Fprintf(&b, "RelayBandwidthRate %s\n", cfg.BandwidthRate)
	}
	if cfg.BandwidthBurst != "" {
		fmt.Fprintf(&b, "RelayBandwidthBurst %s\n", cfg.BandwidthBurst)
	}
	for _, id := range cfg.FamilyID {
		fmt.Fprintf(&b, "FamilyId %s\n", id)
	}
	b.WriteString("ExitRelay 0\n")
	b.WriteString("ExitPolicy reject *:*\n")
	b.WriteString("ExitPolicy reject6 *:*\n")
	sandbox := "0"
	if cfg.Sandbox {
		sandbox = "1"
	}
	fmt.Fprintf(&b, "Sandbox %s\n", sandbox)
	if includeTorrcD {
		fmt.Fprintf(&b, "%%include %s/\n", TorrcD)
	}

	return b.String()
}
