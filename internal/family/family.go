package family

import (
	"context"
	"errors"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"syscall"
	"time"
)

const (
	fetchTimeout = 15 * time.Second
	maxBodyBytes = 4 << 20
)

var fingerprintRE = regexp.MustCompile(`^[0-9A-Fa-f]{40}$`)

// Options configures a Manager.
type Options struct {
	URL             string
	Interval        time.Duration
	MaxDropPct      int
	Path            string
	FingerprintPath string
}

// Manager fetches a MyFamily list and keeps Path in sync.
type Manager struct {
	URL             string
	Interval        time.Duration
	MaxDropPct      int
	Path            string
	FingerprintPath string

	Client *http.Client
	Logf   func(format string, args ...any)
	Signal func(pid int) error
}

// New returns a Manager with a 15 second https-only client. Redirects are
// followed only while they stay on https.
func New(opts Options) *Manager {
	m := &Manager{
		URL:             opts.URL,
		Interval:        opts.Interval,
		MaxDropPct:      opts.MaxDropPct,
		Path:            opts.Path,
		FingerprintPath: opts.FingerprintPath,
		Logf:            log.Printf,
		Signal: func(pid int) error {
			return syscall.Kill(pid, syscall.SIGHUP)
		},
	}
	if m.Interval < 10*time.Minute {
		m.Interval = 10 * time.Minute
	}
	m.Client = &http.Client{
		Timeout: fetchTimeout,
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			if req.URL.Scheme != "https" {
				return fmt.Errorf("refusing redirect to %s", req.URL)
			}
			if len(via) >= 10 {
				return errors.New("stopped after 10 redirects")
			}
			return nil
		},
	}
	return m
}

// Parse reads one fingerprint per line, allowing an optional leading $ and
// # comments. Duplicates are removed and fingerprints are upper-cased.
func Parse(data []byte) ([]string, error) {
	var out []string
	seen := make(map[string]bool)
	for i, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if cut := strings.IndexByte(line, '#'); cut >= 0 {
			line = strings.TrimSpace(line[:cut])
		}
		if line == "" {
			continue
		}
		fp := strings.ToUpper(strings.TrimPrefix(line, "$"))
		if !fingerprintRE.MatchString(fp) {
			return nil, fmt.Errorf("line %d: %q is not a 40-hex fingerprint", i+1, line)
		}
		if seen[fp] {
			continue
		}
		seen[fp] = true
		out = append(out, fp)
	}
	return out, nil
}

// ReadOwnFingerprint reads the relay fingerprint from tor's fingerprint file.
// The file contains a nickname followed by the 40-hex fingerprint.
func ReadOwnFingerprint(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	fields := strings.Fields(string(data))
	if len(fields) < 2 {
		return "", fmt.Errorf("%s: expected a nickname and a fingerprint", path)
	}
	fp := strings.ToUpper(strings.TrimPrefix(fields[1], "$"))
	if !fingerprintRE.MatchString(fp) {
		return "", fmt.Errorf("%s: %q is not a 40-hex fingerprint", path, fields[1])
	}
	return fp, nil
}

// Load reads the MyFamily entries from a file written by Write. A missing file
// is reported as os.ErrNotExist.
func Load(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []string
	seen := make(map[string]bool)
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) == 0 || fields[0] != "MyFamily" {
			continue
		}
		if len(fields) < 2 {
			continue
		}
		for _, entry := range strings.Split(fields[1], ",") {
			fp := strings.ToUpper(strings.TrimPrefix(strings.TrimSpace(entry), "$"))
			if !fingerprintRE.MatchString(fp) {
				return nil, fmt.Errorf("%s: %q is not a 40-hex fingerprint", path, entry)
			}
			if seen[fp] {
				continue
			}
			seen[fp] = true
			out = append(out, fp)
		}
	}
	return out, nil
}

// Write atomically replaces path with a family.conf containing the
// fingerprints. An empty list writes only the header, which tor accepts.
func Write(path string, fingerprints []string) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0700); err != nil {
		return fmt.Errorf("create %s: %w", dir, err)
	}

	var b strings.Builder
	b.WriteString("# generated by torinit, do not edit\n")
	if len(fingerprints) > 0 {
		b.WriteString("MyFamily ")
		for i, fp := range fingerprints {
			if i > 0 {
				b.WriteString(",")
			}
			b.WriteString("$")
			b.WriteString(fp)
		}
		b.WriteString("\n")
	}

	tmp, err := os.CreateTemp(dir, "family.conf.*")
	if err != nil {
		return fmt.Errorf("create temp file in %s: %w", dir, err)
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)

	if _, err := io.WriteString(tmp, b.String()); err != nil {
		tmp.Close()
		return fmt.Errorf("write %s: %w", tmpName, err)
	}
	if err := tmp.Chmod(0600); err != nil {
		tmp.Close()
		return fmt.Errorf("chmod %s: %w", tmpName, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close %s: %w", tmpName, err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return fmt.Errorf("rename %s to %s: %w", tmpName, path, err)
	}
	return nil
}

// Startup makes sure Path exists before tor reads it. It fetches once and
// falls back to the existing file or an empty file on any failure. It never
// blocks tor from starting.
func (m *Manager) Startup() {
	_, statErr := os.Stat(m.Path)
	exists := statErr == nil

	fetched, err := m.fetch(context.Background())
	if err == nil {
		fetched = sortUnique(m.filterOwn(fetched))
		current, loadErr := Load(m.Path)
		if loadErr != nil && !errors.Is(loadErr, os.ErrNotExist) {
			m.Logf("myfamily: cannot read current list from %s: %v", m.Path, loadErr)
		}
		current = sortUnique(current)
		if reason := m.guard(current, fetched); reason != nil {
			err = reason
		} else if equal(current, fetched) && exists {
			return
		} else if writeErr := Write(m.Path, fetched); writeErr != nil {
			err = writeErr
		} else {
			m.Logf("myfamily: wrote %d fingerprints to %s", len(fetched), m.Path)
			return
		}
	}

	m.Logf("myfamily: startup fetch failed: %v", err)
	if exists {
		m.Logf("myfamily: keeping existing %s", m.Path)
		return
	}
	if writeErr := Write(m.Path, nil); writeErr != nil {
		m.Logf("myfamily: cannot write empty %s: %v", m.Path, writeErr)
		return
	}
	m.Logf("myfamily: wrote empty %s", m.Path)
}

// Refresh fetches and applies a new list. It returns true when the file was
// rewritten and tor was signaled.
func (m *Manager) Refresh(pid int) (bool, error) {
	fetched, err := m.fetch(context.Background())
	if err != nil {
		return false, err
	}
	fetched = sortUnique(m.filterOwn(fetched))

	current, err := Load(m.Path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		m.Logf("myfamily: cannot read current list from %s: %v", m.Path, err)
		current = nil
	}
	current = sortUnique(current)

	if reason := m.guard(current, fetched); reason != nil {
		return false, reason
	}
	if equal(current, fetched) {
		return false, nil
	}
	if err := Write(m.Path, fetched); err != nil {
		return false, err
	}
	if pid > 0 {
		if err := m.Signal(pid); err != nil {
			return true, fmt.Errorf("wrote %s but SIGHUP failed: %w", m.Path, err)
		}
	}
	return true, nil
}

// Loop refetches every Interval until stop is closed. pid is the tor
// process to signal when the list changes.
func (m *Manager) Loop(pid int, stop <-chan struct{}) {
	ticker := time.NewTicker(m.Interval)
	defer ticker.Stop()
	for {
		select {
		case <-stop:
			return
		case <-ticker.C:
			changed, err := m.Refresh(pid)
			if err != nil {
				m.Logf("myfamily: refresh failed: %v", err)
				continue
			}
			if changed {
				m.Logf("myfamily: updated %s and sent SIGHUP to tor", m.Path)
			}
		}
	}
}

func (m *Manager) fetch(ctx context.Context) ([]string, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, m.URL, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "torinit")

	resp, err := m.Client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("unexpected HTTP status %s", resp.Status)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, maxBodyBytes+1))
	if err != nil {
		return nil, err
	}
	if len(body) > maxBodyBytes {
		return nil, fmt.Errorf("response is larger than %d bytes", maxBodyBytes)
	}
	return Parse(body)
}

func (m *Manager) filterOwn(fingerprints []string) []string {
	own, err := ReadOwnFingerprint(m.FingerprintPath)
	if err != nil {
		if !errors.Is(err, os.ErrNotExist) {
			m.Logf("myfamily: cannot read own fingerprint from %s: %v", m.FingerprintPath, err)
		}
		return fingerprints
	}
	var out []string
	for _, fp := range fingerprints {
		if fp != own {
			out = append(out, fp)
		}
	}
	if len(out) != len(fingerprints) {
		m.Logf("myfamily: excluded own fingerprint %s", own)
	}
	return out
}

func sortUnique(fingerprints []string) []string {
	seen := make(map[string]bool, len(fingerprints))
	out := make([]string, 0, len(fingerprints))
	for _, fp := range fingerprints {
		if !seen[fp] {
			seen[fp] = true
			out = append(out, fp)
		}
	}
	sort.Strings(out)
	return out
}

// guard rejects an update that would empty a non-empty list or drop more than
// MaxDropPct percent of the current entries.
func (m *Manager) guard(current, fetched []string) error {
	if len(fetched) == 0 && len(current) > 0 {
		return fmt.Errorf("refusing empty update, current list has %d entries", len(current))
	}
	if len(current) == 0 {
		return nil
	}
	inFetched := make(map[string]bool, len(fetched))
	for _, fp := range fetched {
		inFetched[fp] = true
	}
	dropped := 0
	for _, fp := range current {
		if !inFetched[fp] {
			dropped++
		}
	}
	if dropped*100 > m.MaxDropPct*len(current) {
		pct := dropped * 100 / len(current)
		return fmt.Errorf("refusing update, %d of %d entries dropped (%d%% > %d%%)", dropped, len(current), pct, m.MaxDropPct)
	}
	return nil
}

func equal(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}
